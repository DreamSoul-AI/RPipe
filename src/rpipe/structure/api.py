"""Lightweight capabilities exchanged by scientific components."""
from __future__ import annotations

from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any, Protocol, TypeAlias

from .control import AlgorithmConfig


CancelCheck: TypeAlias = Callable[[], None]
ComputationObservation: TypeAlias = dict[str, Any]


class DataPort(Protocol):
    name: str
    source: str
    meta: dict[str, Any]

    def has_split(self, split: str) -> bool: ...
    def dataset(self, split: str) -> Any | None: ...
    def batch_size(self, split: str = 'train') -> int | None: ...
    def iter_batches(self, split: str, *, resumable: bool = True) -> Iterator[Any]: ...
    def steps_per_epoch(self, split: str = 'train') -> int | None: ...
    def rebind_train_steps(self, *, step: int, num_steps: int, step_period: int = 1) -> None: ...
    def training_state(self) -> dict[str, Any] | None: ...
    def restore_training_state(self, state: dict[str, Any]) -> bool: ...
    def to_result_snapshot(self) -> dict[str, Any]: ...
    def close(self) -> None: ...


class ModelPort(Protocol):
    name: str
    source: str
    module: Any
    meta: dict[str, Any]

    def to_result_snapshot(self) -> dict[str, Any]: ...


class SystemPort(Protocol):
    device: str
    logger: Any
    assets_dir: Path
    meta: dict[str, Any]

    def place_module(self, module: Any) -> Any: ...
    def to_result_snapshot(self) -> dict[str, Any]: ...


class TrackerPort(Protocol):
    metrics: Any
    progress: dict[str, Any] | None

    def evaluate(self, split: str, mode: str = 'batch', input: Any = None,
                 output: Any = None) -> dict[str, float]: ...
    def append(self, split: str, n: int = 1, values: dict[str, float] | None = None) -> None: ...
    def has_samples(self, split: str) -> bool: ...
    def segment_mean(self, split: str) -> dict[str, float]: ...
    def save(self, split: str | None = None) -> None: ...
    def reset(self, split: str | None = None) -> None: ...
    def begin_run(self, checkpoint_state: dict[str, Any] | None = None) -> None: ...
    def flush(self, split: str | None = None, *, progress: dict[str, Any] | None = None) -> None: ...
    def flush_state(self) -> None: ...
    def state_dict(self) -> dict[str, Any]: ...
    def load_state_dict(self, state: dict[str, Any] | None) -> None: ...


class AlgorithmPort(Protocol):
    config: AlgorithmConfig
    mode: str

    def compute(self, data: DataPort, model: ModelPort, system: SystemPort,
                tracker: TrackerPort, cancel_check: CancelCheck) -> ComputationObservation: ...
